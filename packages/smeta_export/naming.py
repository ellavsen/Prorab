"""Имя файла документа. Одно место, потому что имя тоже уходит наружу.

ADR-001 нашёл экспортированный XLSX с `user_id` в имени и удалил файл из
репозитория — но не тронул код, который это имя порождает. Пока документ
уходил только автору, ошибка была почти безобидной; документ, который
пересылают заказчику, отдаёт вместе с собой Telegram-идентификатор владельца.

Поэтому имя строит функция, а не f-строка внутри хендлера: у функции есть
подпись, и в неё нечего передать лишнего.
"""

from __future__ import annotations

from datetime import date


def document_filename(
    number: int, ext: str, on: date, version: int | None = None
) -> str:
    """`smeta_no3_20260803.xlsx`, с версией — `smeta_no3_v2_20260803.pdf`.

    Номер сметы человекочитаем и известен обеим сторонам — он в документе и
    в переписке. Время до секунды в имени не нужно: заказчику оно ничего не
    говорит, а различать файлы одного дня помогает версия.
    """
    parts = ["smeta", f"no{number}"]
    if version is not None:
        parts.append(f"v{version}")
    parts.append(on.strftime("%Y%m%d"))
    return f"{'_'.join(parts)}.{ext.lstrip('.')}"
