"""Справочник единиц измерения и нормализация синонимов.

В Sprint 1 ядро умеет распознавать единицу во вводе; запись её в базу —
задача Sprint 2 (ADR-003 по единицам ещё не принят).
"""

from __future__ import annotations

# Канонические формы (docs/money.md §1.1).
UNITS: tuple[str, ...] = (
    "м²", "м³", "м.п.", "м", "см", "мм", "шт", "компл", "т", "кг", "л", "час",
)

_SYNONYMS: dict[str, str] = {
    "м2": "м²", "м^2": "м²", "кв.м": "м²", "кв м": "м²", "квм": "м²",
    "м3": "м³", "м^3": "м³", "куб.м": "м³", "куб м": "м³", "кубм": "м³",
    "пм": "м.п.", "п.м": "м.п.", "п.м.": "м.п.", "мп": "м.п.",
    "шт.": "шт", "штук": "шт", "штуки": "шт",
    "компл.": "компл", "комплект": "компл",
    "т.": "т", "тонн": "т", "тонна": "т",
    "кг.": "кг",
    "л.": "л", "литр": "л",
    "ч": "час", "ч.": "час", "часов": "час",
}


def normalize_unit(raw: str) -> str:
    """Приводит единицу к канонической форме. Неизвестная -> "" (не ошибка)."""
    s = (raw or "").strip().lower()
    if not s:
        return ""
    if s in _SYNONYMS:
        return _SYNONYMS[s]
    for unit in UNITS:
        if s == unit.lower():
            return unit
    return ""
