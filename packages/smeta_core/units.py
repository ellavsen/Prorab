"""Справочник единиц измерения и нормализация синонимов.

В Sprint 1 ядро умеет распознавать единицу во вводе; запись её в базу —
задача Sprint 2 (ADR-003 по единицам ещё не принят).
"""

from __future__ import annotations

# Канонические формы (docs/money.md §1.1).
# «точка» и «смена» — не упаковка, а настоящие единицы работ: точка в
# электромонтаже и смена в повремёнке. Без них цена «за точку» неотличима от
# цены «за штуку» (ADR-016). Мешок, рулон, лист и упаковка канона не получают
# намеренно: это тара, а не единица.
UNITS: tuple[str, ...] = (
    "м²", "м³", "м.п.", "м", "см", "мм", "шт", "компл", "т", "кг", "л", "час",
    "точка", "смена",
)

_SYNONYMS: dict[str, str] = {
    "м2": "м²", "м^2": "м²", "кв.м": "м²", "кв м": "м²", "квм": "м²",
    "м3": "м³", "м^3": "м³", "куб.м": "м³", "куб м": "м³", "кубм": "м³",
    "пм": "м.п.", "п.м": "м.п.", "п.м.": "м.п.", "мп": "м.п.",
    "шт.": "шт", "штук": "шт", "штуки": "шт",
    "компл.": "компл", "комплект": "компл",
    "т.": "т", "тонн": "т", "тонна": "т",
    "кг.": "кг",
    "л.": "л", "литр": "л",
    "ч": "час", "ч.": "час", "часов": "час",
    "точек": "точка", "точки": "точка", "точку": "точка",
    "смен": "смена", "смены": "смена", "смену": "смена",
    "день": "смена", "дня": "смена", "дней": "смена", "дни": "смена",
}


def default_unit(category: str) -> str:
    """Единица по умолчанию, когда пользователь её не указал (ADR-006).

    Подстановка обязана быть видимой: вызывающий сообщает о ней пользователю,
    иначе это тихое домысливание данных.
    """
    return "шт" if str(category) == "material" else "м²"


def unit_decision(unit: str, unit_spoken: str) -> str:
    """Канон best-effort: явный, иначе выведенный из сказанного, иначе "".

    Неуверенность здесь не беда: единица не участвует в арифметике,
    qty × price считается одинаково при любом каноне (ADR-015).
    """
    return normalize_unit(unit) or normalize_unit(unit_spoken)


def can_substitute_price(
    unit: str, source_unit: str | None = None, blocking_enabled: bool = True
) -> bool:
    """Можно ли подставлять цену за пользователя.

    Единственный случай, когда неоднозначная единица опасна. Названную
    человеком цену она не портит: «20 мешков по 350» это 7000 при любом
    каноне. Но подстановка без подтверждённой единицы даёт ошибку в разы —
    «350 за мешок» против «350 за кг» (ADR-015).

    Без source_unit вопрос прежний: годится ли эта единица под чужое число
    неизвестной привязки. С source_unit вопрос точнее — та же ли это
    величина, что у цены-источника; разные каноны не сходятся никогда, и
    цена за м² не подставляется в позицию в м.п.

    Про случай «канона нет ни у той, ни у другой» эта функция не судит: ей
    нечем отличить «мешок» от «мешка». Сказанное слово сравнивает
    smeta_prices.same_unit, и он же зовёт эту функцию для канонической
    половины правила — чтобы правило осталось одно (ADR-017).
    """
    if not blocking_enabled:
        return True
    canon = normalize_unit(unit)
    if source_unit is None:
        return bool(canon)
    return bool(canon) and canon == normalize_unit(source_unit)


def normalize_unit(raw: str) -> str:
    """Приводит единицу к канонической форме. Неизвестная -> "" (не ошибка)."""
    s = (raw or "").strip().lower()
    if not s:
        return ""
    if s in _SYNONYMS:
        return _SYNONYMS[s]
    for unit in UNITS:
        if s == unit.lower():
            return unit
    return ""
