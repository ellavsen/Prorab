"""Сопоставление наименований: две ступени поверх точного совпадения.

Механизмов здесь два, и это результат замера, а не вкуса. Расстояние между
строками лечит опечатки и не лечит лишние слова: «Грутновка» отстоит от
«Грунтовки» на 0.889 и проходит порог, а «Стяжка пола» от «стяжки» — на 0.706
и не пройдёт ни при каком разумном пороге. Опустить порог до 0.70 нельзя:
тогда сходятся марки, а это ошибка в деньгах.

Вложенность множеств токенов решает вторую беду и первую не решает вовсе:
у «Грутновки» и «Грунтовки» общих токенов нет — искажён сам токен.

Поэтому ступени идут подряд, и порядок между ними важен: опечатка — более
сильное утверждение, чем лишнее слово, и проверяется первой. На каждой ступени
двое кандидатов означают молчание: подсказка от чужой позиции дороже
отсутствия подсказки (ADR-027).
"""

from __future__ import annotations

import difflib
from collections.abc import Iterable

# Порог автопривязки высокий намеренно: цена ошибки — подсказка от чужой
# позиции. Ниже порога — молчание, а не догадка.
FUZZY_CUTOFF = 0.87

# Сколько лишних слов прощается при вложенности. Замер по 478 написаниям
# справочника: 1 слово — 3 неоднозначных, 2 слова — 5, дальше не растёт
# (ADR-018).
MAX_EXTRA_TOKENS = 2


def _graded(key: str) -> set[str]:
    """Токены, несущие цифру: марка, диаметр, сечение.

    М400 и М500 отличаются одним символом из одиннадцати, поэтому по
    расстоянию они — опечатка друг друга, а по смыслу разные материалы с
    разной ценой. То же у «бетон М200/М300» и «кабель 3х1.5 / 3х2.5».
    Это тот же запрет, что уже записан в normalize.py: размер обязан
    сохраниться, иначе 12 мм сравняется с 16 мм.
    """
    return {token for token in key.split() if any(sign.isdigit() for sign in token)}


def by_typo(key: str, keys: Iterable[str]) -> list[str]:
    """Первая ступень: искажённое написание того же самого.

    Цифры при этом обязаны совпасть. Без этой проверки замер по справочнику
    даёт 15 пар, ведущих к чужой позиции, — включая цемент М400 → М500.
    С проверкой остаётся 2, и обе недостижимы: это написания, которые сами
    лежат в индексе, то есть до второй ступени дело не доходит.
    """
    hits = difflib.get_close_matches(key, list(keys), n=2, cutoff=FUZZY_CUTOFF)
    return [hit for hit in hits if _graded(hit) == _graded(key)]


def by_containment(key: str, keys: Iterable[str]) -> list[str]:
    """Вторая ступень: то же самое, сказанное короче или длиннее.

    «Стяжка» и «Стяжка пола», «Покраска стен» и «Покраска стен 3 слоя».
    Требуется строгая вложенность множеств, а не пересечение: у «цемент М400»
    и «цемент М500» пересечение непусто, и по нему они сошлись бы.

    Ограничение на число лишних слов нужно с другого края: «стен» вложено в
    «покраска стен 3 слоя», не будучи ничем.
    """
    wanted = set(key.split())
    if not wanted:
        return []
    found = []
    for other in keys:
        have = set(other.split())
        small, big = sorted((wanted, have), key=len)
        if small < big and len(big) - len(small) <= MAX_EXTRA_TOKENS:
            found.append(other)
    return found


def candidates(key: str, keys: Iterable[str], *, nested: bool = True) -> list[str]:
    """Кандидаты по первой сработавшей ступени. Дальше судит вызывающий.

    Возвращается список, а не один ключ: у справочника два написания одной
    позиции — это один кандидат, а не два, и знает об этом только он.

    nested=False отключает вторую ступень. Так её зовёт история цен: там
    кандидаты — прошлые наименования самого пользователя, и отличить среди них
    работу от материала нечем — `price_history` категории не хранит. «ГКЛ» и
    «ГКЛ монтаж» вложены друг в друга, а цена у них разная в разы.
    """
    if not key:
        return []
    keys = list(keys)
    if key in keys:
        return [key]
    typo = by_typo(key, keys)
    if typo or not nested:
        return typo
    return by_containment(key, keys)


def resolve(key: str, keys: Iterable[str], *, nested: bool = True) -> str | None:
    """Один ключ или ничего. Двое кандидатов — это молчание, а не выбор."""
    found = set(candidates(key, keys, nested=nested))
    return found.pop() if len(found) == 1 else None
