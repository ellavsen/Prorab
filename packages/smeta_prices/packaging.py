"""Словоформы тары. Закрытый список, без морфологии.

Тара — не единица измерения: в мешке бывает и 25 кг, и 50, поэтому канона у
неё нет и не будет (ADR-016). Но «мешков» и «мешок» — одно слово в падежах, и
считать их разными значило бы промолчать там, где прораб сказал ровно то же
самое (ADR-017).

Список ЗАКРЫТЫЙ намеренно. Стеммер или морфоанализатор однажды сведёт «листов»
и «литров» к одной основе, и мы узнаем об этом из кривой сметы, а не из
красного теста — ровно как чуть не случилось с «т.», где «точка» молча
переехала бы тонну.

Поэтому формы объявлены группами, а словарь собирается с проверкой: одна форма
у двух баз — исключение при импорте, а не последняя выигравшая.
"""

from __future__ import annotations

# Первая в группе — базовая форма. Остальные приводятся к ней.
FORM_GROUPS: tuple[tuple[str, ...], ...] = (
    ("мешок", "мешка", "мешки", "мешке", "мешком", "мешков", "мешкам", "мешками"),
    ("рулон", "рулона", "рулоны", "рулоне", "рулоном", "рулонов", "рулонам"),
    ("лист", "листа", "листы", "листе", "листом", "листов", "листам"),
    ("упаковка", "упаковки", "упаковке", "упаковку", "упаковкой", "упаковок",
     "упак", "упак.", "уп", "уп."),
    ("пачка", "пачки", "пачке", "пачку", "пачкой", "пачек", "пачкам"),
    ("ведро", "ведра", "ведре", "ведром", "ведер", "ведрам", "ведрами"),
    ("банка", "банки", "банке", "банку", "банкой", "банок", "банкам"),
    ("коробка", "коробки", "коробке", "коробку", "коробкой", "коробок"),
    ("бухта", "бухты", "бухте", "бухту", "бухтой", "бухт"),
    ("паллета", "паллеты", "паллете", "паллету", "паллетой", "паллет",
     "поддон", "поддона", "поддоны", "поддонов"),
    ("канистра", "канистры", "канистре", "канистру", "канистрой", "канистр"),
    ("тюбик", "тюбика", "тюбики", "тюбике", "тюбиков"),
    ("бобина", "бобины", "бобине", "бобину", "бобиной", "бобин"),
)


class FormCollision(ValueError):
    """Одна словоформа у двух видов тары. Тот же класс ошибки, что дубль «т.»."""


def build_forms(groups: tuple[tuple[str, ...], ...]) -> dict[str, str]:
    """Группы -> словарь формы. Падает на коллизии, а не разрешает её молча."""
    forms: dict[str, str] = {}
    for group in groups:
        base = group[0]
        for form in group:
            existing = forms.get(form)
            if existing is not None and existing != base:
                raise FormCollision(
                    f"словоформа {form!r} принадлежит и {existing!r}, и {base!r}"
                )
            forms[form] = base
    return forms


FORMS: dict[str, str] = build_forms(FORM_GROUPS)
BASES: frozenset[str] = frozenset(group[0] for group in FORM_GROUPS)
